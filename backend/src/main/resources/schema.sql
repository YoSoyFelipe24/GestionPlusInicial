CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, nombre VARCHAR(120) NOT NULL, correo VARCHAR(180) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS clientes (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, nombre VARCHAR(120) NOT NULL, correo VARCHAR(180) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS productos (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, nombre VARCHAR(120) NOT NULL, precio DECIMAL(12,2) NOT NULL, stock INT NOT NULL
);
CREATE TABLE IF NOT EXISTS ventas (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, cliente_id BIGINT NOT NULL, total DECIMAL(12,2) NOT NULL, fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (cliente_id) REFERENCES clientes(id)
);
CREATE TABLE IF NOT EXISTS venta_detalle (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, venta_id BIGINT NOT NULL, producto_id BIGINT NOT NULL,
 cantidad INT NOT NULL, precio_unitario DECIMAL(12,2) NOT NULL, subtotal DECIMAL(12,2) NOT NULL,
 FOREIGN KEY (venta_id) REFERENCES ventas(id), FOREIGN KEY (producto_id) REFERENCES productos(id)
);
CREATE TABLE IF NOT EXISTS facturas (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, venta_id BIGINT NOT NULL UNIQUE, monto DECIMAL(12,2) NOT NULL, emitida_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (venta_id) REFERENCES ventas(id)
);
